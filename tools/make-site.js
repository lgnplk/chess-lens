// Build site/: everything Chess Lens needs to run on a static host, ready to upload. Works on Netlify and Cloudflare Pages.
//   node tools/make-site.js
// Netlify:    drag the site folder onto https://app.netlify.com/drop (or: npx netlify-cli deploy --prod --dir site)
// Cloudflare: Workers & Pages → Create → Pages → Upload assets, drop the site folder (or: npx wrangler pages deploy site)
//
// serve.js isn't running on a host, so the PGN Mentor relay becomes a proxy rule in _redirects on Netlify and
// _worker.js on Cloudflare (the same two paths serve.js allows); the Maia models get the long cache serve.js
// gives them; models over 24 MB are split into pieces (Cloudflare's per-file cap).
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.join(__dirname, '..');
const dest = path.join(root, 'site');
// the comparison page and its legacy model aren't part of the app
const SKIP_JS = new Set(['maia-eval.js', 'bot-legacy.js']);

const scripts = fs.readdirSync(path.join(root, 'js')).filter(f => f.endsWith('.js') && !SKIP_JS.has(f));
const bad = scripts.filter(f => spawnSync(process.execPath, ['--check', path.join(root, 'js', f)]).status !== 0);
if (bad.length) { console.error('Not building — syntax errors in: ' + bad.join(', ')); process.exit(1); }

fs.rmSync(dest, { recursive: true, force: true });
fs.mkdirSync(path.join(dest, 'js'), { recursive: true });
fs.mkdirSync(path.join(dest, 'models'));
fs.cpSync(path.join(root, 'index.html'), path.join(dest, 'index.html'));
fs.cpSync(path.join(root, 'css'), path.join(dest, 'css'), { recursive: true });
for (const f of fs.readdirSync(path.join(root, 'js'))) {
  if (SKIP_JS.has(f) || !/\.(js|json)$/.test(f)) continue;
  fs.cpSync(path.join(root, 'js', f), path.join(dest, 'js', f));
}
// Cloudflare Pages refuses files over 25 MiB, so a big model ships as pieces plus a list (model.onnx.parts.json);
// js/maia-worker.js reads the list and joins the pieces. Every model gets a list, so loading works the same way.
const PART_BYTES = 24 * 1024 * 1024;
for (const f of fs.readdirSync(path.join(root, 'models'))) {
  if (!f.endsWith('.onnx')) continue;
  const buf = fs.readFileSync(path.join(root, 'models', f)), parts = [];
  for (let i = 0, off = 0; off < buf.length; i++, off += PART_BYTES) {
    const name = buf.length > PART_BYTES ? `${f}.part${i}` : f;
    fs.writeFileSync(path.join(dest, 'models', name), buf.subarray(off, off + PART_BYTES));
    parts.push(name);
  }
  fs.writeFileSync(path.join(dest, 'models', f + '.parts.json'), JSON.stringify({ bytes: buf.length, parts }));
}

fs.writeFileSync(path.join(dest, '_redirects'), [
  '# PGN Mentor does not allow browser cross-origin requests; Netlify fetches these two kinds of path for the page',
  '/relay/pgnmentor/files.html     https://www.pgnmentor.com/files.html      200',
  '/relay/pgnmentor/players/*      https://www.pgnmentor.com/players/:splat  200',
  '',
].join('\n'));
fs.writeFileSync(path.join(dest, '_headers'), [
  '# the Maia models are large and never change: let browsers keep them for a week',
  '/models/*',
  '  Cache-Control: public, max-age=604800',
  '',
].join('\n'));

// Cloudflare Pages: _redirects can't proxy to another site, so this worker relays the same two PGN Mentor paths
// (and gives the models their long cache). Netlify ignores it and uses _redirects/_headers above.
fs.writeFileSync(path.join(dest, '_worker.js'), `// Cloudflare Pages only (Netlify ignores this file). Generated by tools/make-site.js.
const PGNMENTOR_OK = /^(files\\.html|players\\/[A-Za-z0-9_-]+\\.zip)$/;
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname.startsWith('/relay/pgnmentor/')) {
      const rel = url.pathname.slice('/relay/pgnmentor/'.length);
      if (!PGNMENTOR_OK.test(rel)) return new Response('Not allowed', { status: 403 });
      const r = await fetch('https://www.pgnmentor.com/' + rel, { cf: { cacheEverything: true, cacheTtl: 86400 } });
      if (!r.ok) return new Response(null, { status: r.status });
      return new Response(r.body, { headers: { 'Content-Type': r.headers.get('content-type') || 'application/octet-stream', 'Cache-Control': 'max-age=86400' } });
    }
    const res = await env.ASSETS.fetch(request);
    if (!url.pathname.startsWith('/models/') || !res.ok) return res;
    const out = new Response(res.body, res);
    out.headers.set('Cache-Control', 'public, max-age=604800');
    return out;
  },
};
`);
// a real 404 page, so a missing file isn't answered with index.html on hosts that fall back to it
fs.writeFileSync(path.join(dest, '404.html'), '<!doctype html><meta charset="utf-8"><title>Not found</title><p>Not found. <a href="/">Chess Lens</a></p>\n');

// every local file index.html refers to must be in the folder
const html = fs.readFileSync(path.join(dest, 'index.html'), 'utf8');
const refs = [...html.matchAll(/(?:src|href)="([^"#:]+)"/g)].map(m => m[1]).filter(r => !r.startsWith('//'));
const missing = refs.filter(r => !fs.existsSync(path.join(dest, r)));
if (missing.length) { console.error('Missing from site/: ' + missing.join(', ')); process.exit(1); }

let bytes = 0, files = 0;
const walk = d => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else { bytes += fs.statSync(p).size; files++; } } };
walk(dest);
console.log(`site/ ready: ${files} files, ${(bytes / 1e6).toFixed(1)} MB (${refs.length} references checked)`);
